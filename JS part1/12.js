// booleans & comparison operator 

// booleans 
// true, false 

let num1 = 7;
let num2 = "7";

console.log(num1<num2);

// == vs === 
console.log(num1 === num2);

// != vs !==
console.log(num1 != num2) // type coercion happens here, thus false it will, it should have been true since types are different
console.log(num1 !== num2); // here it will be true, since types are different and coercion won't happen

